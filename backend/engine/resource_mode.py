# -*- coding: utf-8 -*-
"""资源对话模式分类器（单步4）：修改(定向指令)/生成(非指向修正) 二分。
纯规则零 LLM——路由路径零网络依赖、全确定性可测；赛后可加 fast LLM 兜底。
判定契约（设计文档《审核、资源生成》二.1：含具体替换文本 → 修改；否则 → 生成）：
- 定向指令（把X改成Y/换成/替换为/删除第N段…）→ edit（直连修订，无审核）
- 纯提问（?结尾/是什么/为什么…）→ edit 分支的 💬 协议承接（不产版本）
- 指出问题但无正确信息（错/不对/优化…无定向指令）→ gen（检索供证 + 断言审核）
- 兜底默认 gen（非指向修正走审核链路——安全侧）
"""
import re

# 定向指令信号：含具体替换目标
_EDIT_RE = re.compile(
    r"把[^\n]{0,24}改成"
    r"|改成[「“'\"『]"
    r"|换成[^\n]{0,24}"
    r"|改为[^\n]{0,24}"
    r"|替换成|替换为"
    r"|(删除|删掉|去掉)[^\n]{0,10}(段|行|节|部分|小节)"
    r"|第[一二三四五六七八九十\d]+[段落章节][^\n]{0,12}(改|换|删|扩|缩)"
    r"|改得更|改得[简详精]"
)
# 提问信号：💬 协议由 edit 分支承接（回答不产版本）
_QUESTION_RE = re.compile(
    r"[?？]\s*$"
    r"|^(是什么|为什么|怎么|如何|什么是|哪些|有哪些|能否|可不可以|能不能|好了吗)"
)
# 修正/改进诉求信号：无定向指令时 → 生成模式（系统供证）
_MODIFY_RE = re.compile(
    r"错|不对|有误|更新|优化|润色|扩写|精简|缩短|补充|重写|重新生成|再改|改一下|修改"
)


def classify_resource_mode(text) -> str:
    """返回 "edit"（定向修改/提问——edit 分支承接）| "gen"（非指向修正——生成管线承接）。"""
    t = (text or "").strip()
    if not t:
        return "gen"
    if _EDIT_RE.search(t):
        return "edit"
    if _QUESTION_RE.search(t):
        return "edit"
    return "gen"
